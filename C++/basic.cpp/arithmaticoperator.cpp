#include<iostream>
using namespace std;

int main() {
    int x = 5;
    int y = 2;
    
    // Addition
    cout << "x + y = " << x + y << endl;
    
    // Subtraction
    cout << "x - y = " << x - y << endl;
    
    // Multiplication
    cout << "x * y = " << x * y << endl;
    
    // Division (as float for decimal result)
    cout << "x / y = " << (float)x / y << endl;
    
    // Modulus (remainder)
    cout << "x % y = " << x % y << endl;
    
    return 0;
}